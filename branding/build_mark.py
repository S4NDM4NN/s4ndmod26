#!/usr/bin/env python3
"""Generates branding/s4nd-mark.svg, s4nd-mark-flat.svg and s4nd-icon.svg.

Run from the repo root:  python3 branding/build_mark.py
Then copy the SVGs where they are used (see branding/README.md) and regenerate the PNGs/.ico.

Everything is on a 66-unit grid.  Parts that meet are made to OVERLAP rather than abut, and the red gets a
hairline stroke, so no anti-aliasing seam can show the white backing through the red.
"""
import xml.dom.minidom

RED, WHITE = "#cf1b1f", "#ffffff"
M = 1.1                      # white outline width (units)
XO, HW, TIP = 41, 4, 35      # outer edge of heads/body (mirrored: 25), head width, beak tip x
SLOPE, GAP, STRUT = 0.25, 0.5, 3
S1 = S2 = 1                  # gaps between bar 1/2 and bar 2/3
OVERLAP = 1                  # how far abutting shapes are pushed into each other
HAIR = 0.15                  # hairline red stroke closing any remaining seam


def poly(P):
    return "M" + " L".join(f"{x:g} {y:g}" for x, y in P) + " Z"


def mirror(P):
    return [(66 - x, y) for x, y in P]


XI, XL = XO - HW, 66 - XO
LI, RI = 33 - GAP, 33 + GAP
y1 = 4; b1 = y1 + 2; y2 = b1 + S1; b2 = y2 + 2; y3 = b2 + S2; b3 = y3 + 2     # bars: 4-6, 7-9, 10-12
top = y3; mid = top + 5; outer = top + 10
yb = lambda x: outer + SLOPE * ((XO - 33) - abs(x - 33))
yt = lambda x: yb(x) - 2
tipx = lambda y: 64 - (y - 4)          # all three tips lie on one 45-degree line
floor = b2 - 3                         # bar 2 is 3 units thick where it meets the head

head = [(XO, 0), (TIP, 1), (TIP, 3), (XI, 3), (XI, b2), (XO, b2)]
# bar 1/2 unit: pushed OVERLAP units into the head so the two never share just an edge
feather = [(XO - OVERLAP, b2), (XO - OVERLAP, floor), (39 + floor, floor), (43, 4), (64, 4), (tipx(b1), b1),
           (45 + STRUT, b1), (45 + STRUT + S1, y2), (tipx(y2), y2), (tipx(b2), b2)]
# lower bar: runs 2 units into the numeral's top bar (same rows), so there is no seam where they meet
bar3 = [(XO - 2, y3), (tipx(y3), y3), (tipx(b3), b3), (XO - 2, b3)]
two = [(XL, top), (LI, top), (LI, mid + 2), (XL + 2, mid + 2), (XL + 2, yt(XL + 2)), (LI, yt(LI)), (LI, yb(LI)),
       (XL, yb(XL)), (XL, mid), (LI - 2, mid), (LI - 2, top + 2), (XL, top + 2)]
six = [(RI, top), (XO, top), (XO, top + 2), (RI + 2, top + 2), (RI + 2, mid), (XO, mid), (XO, yb(XO)), (RI, yb(RI))]
hole = [(RI + 2, mid + 2), (XO - 2, mid + 2), (XO - 2, yt(XO - 2)), (RI + 2, yt(RI + 2))]
bottom = yb(33)

# the left bar 3 must also reach into the "2": mirror() does that
red = "\n    ".join(f'<path d="{poly(p)}"/>' for p in
                    [head, feather, bar3, mirror(head), mirror(feather), mirror(bar3), two]) \
    + "\n    " + f'<path fill-rule="evenodd" d="{poly(six)} {poly(hole)}"/>'
wing = [(XO, 4), (64, 4), (tipx(b3), b3), (XO, b3)]
body = [(XL, top), (XO, top), (XO, yb(XO)), (33, bottom), (XL, yb(XL))]
fills = "\n    ".join(f'<path d="{poly(p)}"/>' for p in (wing, mirror(wing), body))
# Shapes the white outline is built from.  The numerals are NOT expanded individually: their inner bottom
# corners would each push a mitred corner past the centre line and leave a small tab below the V.  They sit
# entirely inside `body`, so the outline's bottom is the clean offset of the body's V.
outline_src = "\n    ".join(f'<path d="{poly(p)}"/>' for p in
                          [head, feather, bar3, mirror(head), mirror(feather), mirror(bar3)])

doc = f'''<!-- Flat red on a 66-unit grid.  One stroke weight (2 units) for every bar and numeral stroke; the gaps
       between the three wing bars are 1 unit (the original's are ~0.8 and ~1.2).  All cuts are 45 degrees except the
       heads' top edge, which slopes into a 2-unit hook.  The three wing tips lie on one 45-degree line
       (x = 64 - (y-4)).  The top bar's inner end is cut back on a 45-degree line and the slot under it closes on a
       parallel line {STRUT} units further out, so bars 1 and 2 join through a strut about one bar thick; the notch
       beside the head has its floor at y={floor}, so bar 2 is 3 units thick where it meets the head.  The heads'
       outer edge, the lower bar's end and the numerals' outer edge share one vertical line (x={XO}, mirrored {XL}).
       Numerals are 12 tall with a V bottom and a 1-unit gap between them.  The white outline is the silhouette
       (gaps and the "6" counter filled) expanded by {M:g} unit; transparent outside.  Generated by
       branding/build_mark.py; parts overlap and the red has a hairline stroke so no seam shows white. -->'''


def build(outline, vb):
    back = f'''<g fill="{WHITE}" stroke="{WHITE}" stroke-width="{2 * M:g}" stroke-linejoin="miter" stroke-miterlimit="4">
    {fills}
    {outline_src}
  </g>
  ''' if outline else ""
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" role="img" aria-label="S4NDMoD26">
  <title>S4NDMoD26</title>
  {doc}
  {back}<g fill="{RED}" stroke="{RED}" stroke-width="{HAIR:g}" stroke-linejoin="miter">
    {red}
  </g>
</svg>
'''


import math
apex = M / math.sin(math.atan2(1, SLOPE))          # vertical reach of the mitred V apex below its vertex
cy = bottom / 2
outputs = {
    "branding/s4nd-mark.svg": build(True, f"{-M:g} {-M:g} {66 + 2 * M:g} {bottom + M + apex + 0.05:g}"),
    "branding/s4nd-mark-flat.svg": build(False, f"0 0 66 {bottom:g}"),
    "branding/s4nd-icon.svg": build(True, f"10 {cy - 23:g} 46 46"),
}
for path, svg in outputs.items():
    xml.dom.minidom.parseString(svg)
    open(path, "w").write(svg)
print("wrote", ", ".join(outputs))
